import { it, expect, vi } from 'vitest';
const { handlers, dialog } = vi.hoisted(() => ({ handlers: new Map<string, (...args: any[]) => Promise<any>>(), dialog: { showSaveDialog: vi.fn(), showOpenDialog: vi.fn() } }));
vi.mock('electron', () => ({ ipcMain: { handle: (name: string, action: any) => handlers.set(name, action), removeHandler: (name: string) => handlers.delete(name) }, dialog }));
import { registerHandlers } from '../../src/main/ipc/registerHandlers.js';
import { channels } from '../../src/shared/api.js';
it('allows only the trusted main frame, validates inputs, handles cancellations and prevents concurrent operations', async () => {
  const frame = { url: 'file:///app/index.html' };
  const window = { webContents: { mainFrame: frame } };
  const event = { sender: window.webContents, senderFrame: frame };
  const service = { state: () => ({ current: null }), changeHierarchy: vi.fn(), create: vi.fn(), open: vi.fn(), save: vi.fn(), updateProject: vi.fn(), saveSettings: vi.fn(), config: { get: () => ({ recentProjects: ['/allowed'] }) } };
  const unregister = registerHandlers(window as any, service as any, frame.url);
  expect((await handlers.get(channels.state)!({ sender: {}, senderFrame: frame })).ok).toBe(false);
  expect((await handlers.get(channels.state)!({ sender: window.webContents, senderFrame: { url: frame.url } })).ok).toBe(false);
  frame.url = 'https://evil.example'; expect((await handlers.get(channels.state)!(event)).ok).toBe(false); frame.url = 'file:///app/index.html';
  expect((await handlers.get(channels.state)!(event)).ok).toBe(true);
  expect((await handlers.get(channels.openRecent)!(event, '../arbitrary')).ok).toBe(false);
  expect((await handlers.get(channels.openRecent)!(event, 3)).ok).toBe(false);
  await handlers.get(channels.openRecent)!(event, 0); expect(service.open).toHaveBeenCalledWith('/allowed');
  dialog.showOpenDialog.mockResolvedValue({ canceled: true, filePaths: [] });
  expect((await handlers.get(channels.openProject)!(event)).ok).toBe(true);
  dialog.showOpenDialog.mockResolvedValue({ canceled: false, filePaths: ['/chosen'] });
  await handlers.get(channels.openProject)!(event); expect(service.open).toHaveBeenCalledWith('/chosen');
  expect((await handlers.get(channels.createProject)!(event, 'X', '../')).ok).toBe(false);
  dialog.showSaveDialog.mockResolvedValue({ canceled: false, filePath: '/new' });
  await handlers.get(channels.createProject)!(event, 'Project', 'GS'); expect(service.create).toHaveBeenCalledWith('/new', 'Project', 'GS');
  await handlers.get(channels.changeHierarchy)!(event, { action: 'addModule' }); expect(service.changeHierarchy).toHaveBeenCalledWith({ action: 'addModule' });
  await handlers.get(channels.updateProject)!(event, { projectName: 'X' }); expect(service.updateProject).toHaveBeenCalled();
  await handlers.get(channels.saveSettings)!(event, {}); expect(service.saveSettings).toHaveBeenCalled();
  let finish!: () => void; service.save.mockImplementation(() => new Promise<void>(resolve => { finish = resolve; }));
  const saving = handlers.get(channels.saveProject)!(event);
  expect((await handlers.get(channels.state)!(event)).error).toContain('in progress');
  finish(); await saving; unregister(); expect(handlers.size).toBe(0);
});
